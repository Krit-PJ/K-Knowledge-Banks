// Builds frontend/templates.json: one starting JSON per record type for the console's draft editor, derived from the
// synthetic No-AI slice records (core/test/helpers.js) so templates stay schema-shaped. Reference IDs are placeholders
// (REPLACE_WITH_<Type>_ID) that the validator rejects until a human replaces them with real draft IDs.
//   npm run build:templates            write    ·    npm run build:templates -- --check
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { sliceDrafts, DRAFT_KEYS } from '../core/test/helpers.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const TEMPLATES_FILE = path.join(ROOT, 'frontend', 'templates.json');
const TYPES = { S: 'Study', R: 'Report', E: 'Evidence', ER: 'Evidence', AR: 'AnalysisRun', X: 'Result', F: 'Finding', CF: 'ClaimFrame', Cl: 'Claim', P: 'ReviewProtocol' };

export function buildTemplates() {
  const ids = Object.fromEntries(DRAFT_KEYS.map((k) => [k, `REPLACE_WITH_${TYPES[k]}_ID`]));
  const out = { note: 'Generated by scripts/build-templates.mjs from synthetic fixtures. Replace every REPLACE_WITH_* value; no real data.', templates: {} };
  for (const [, rec] of sliceDrafts(ids, { id: 'REPLACE_WITH_SourceAsset_ID', type: 'SourceAsset', revision: 1 })) {
    if (!out.templates[rec.type]) out.templates[rec.type] = rec;
  }
  return `${JSON.stringify(out, null, 2)}\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = buildTemplates();
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(TEMPLATES_FILE) || fs.readFileSync(TEMPLATES_FILE, 'utf8') !== text) { console.error('frontend/templates.json is out of date'); process.exit(1); }
    console.log('frontend/templates.json is up to date');
  } else { fs.writeFileSync(TEMPLATES_FILE, text); console.log('wrote frontend/templates.json'); }
}
